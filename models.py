from datetime import datetime
from flask_sqlalchemy import SQLAlchemy
db=SQLAlchemy()
def now(): return datetime.utcnow()
class Case(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    reference=db.Column(db.String(24),unique=True,nullable=False,index=True)
    created_at=db.Column(db.DateTime,default=now,nullable=False,index=True)
    language=db.Column(db.String(8),default="en",nullable=False)
    name=db.Column(db.String(100),nullable=False)
    email=db.Column(db.String(254),nullable=False,index=True)
    platform=db.Column(db.String(40),nullable=False)
    handle=db.Column(db.String(200))
    phone=db.Column(db.String(32))
    incident_date=db.Column(db.String(10))
    category=db.Column(db.String(40),nullable=False)
    priority=db.Column(db.String(16),nullable=False)
    evidence_url=db.Column(db.String(500))
    description=db.Column(db.Text,nullable=False)
    preferred_next_step=db.Column(db.String(20),nullable=False)
    status=db.Column(db.String(24),default="new",nullable=False,index=True)
    risk_score=db.Column(db.Integer,default=0,nullable=False)
    risk_flags_json=db.Column(db.Text,default="[]",nullable=False)
    notes=db.relationship("AdminNote",backref="case",cascade="all,delete-orphan")
class AdminNote(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    case_id=db.Column(db.Integer,db.ForeignKey("case.id"),nullable=False,index=True)
    created_at=db.Column(db.DateTime,default=now)
    author=db.Column(db.String(80),nullable=False)
    body=db.Column(db.Text,nullable=False)
class AuditLog(db.Model):
    id=db.Column(db.Integer,primary_key=True)
    created_at=db.Column(db.DateTime,default=now,index=True)
    actor=db.Column(db.String(80),nullable=False)
    action=db.Column(db.String(80),nullable=False)
    case_reference=db.Column(db.String(24))
    detail=db.Column(db.String(500))
